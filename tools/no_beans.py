#!/usr/bin/env python
"""Generate the no-beans pack: CobbleCuisine's beans can never be eaten, because eating one crashes the server.

THE FAULT (2026-10-21, crash-2026-10-21_17.45.27-server.txt): CobbleCuisine 2.0.1 (cobblecuisine-2.0.1-1.7.rc1.jar,
built for Cobblemon 1.7 and the newest release on Modrinth that day) calls BeanItem.use with a signature Cobblemon
1.8.2 no longer has: java.lang.NoSuchMethodError in the server tick loop, which stops the server for everyone. The owner
used a friendship bean and the server went down; the owner chose "block beans only" over removing the mod.

THE RULE. A bean must never reach a hand, so:
  loot      the bean crop's block loot table (cobblecuisine:blocks/bean_crop) is written back dropping nothing;
  recipes   every CobbleCuisine recipe that makes or uses a bean is written back holding only Fabric API's
            fabric:load_conditions with a condition that never passes (the closure tools/key_ball.py uses), so the
            server skips it at load;
  sweep     every SWEEP_TICKS, `clear @a <bean>` for each bean, so a bean from any other source (an old chest, a
            trade, a drop we do not know of) is gone within a second.
It touches only the bean items listed below; CobbleCuisine's other foods are untouched (not known to crash; NOT tested).

  python tools/no_beans.py            # write build/datapacks/cobblers_no_beans
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

import function_limits  # noqa: E402

PACK_FORMAT = 48  # Minecraft 1.21.1
NS = "cobblers"
DEFAULT_OUT = ROOT / "build" / "datapacks" / "cobblers_no_beans"
SWEEP_TICKS = 20
# the BeanItem items: the seven the live server's item registry knows (each tested with `clear @a <id> 0` over RCON,
# 2026-10-22). The jar also ships models for patterned_indigo_bean and patterned_violet_bean, but no such items are
# registered, and one unknown id makes the server refuse the whole sweep function (it did, at the 2026-10-22 install)
BEANS = ("red_bean", "orange_bean", "yellow_bean", "green_bean", "blue_bean", "indigo_bean", "violet_bean")
# every recipe in the jar whose name names a bean (read 2026-10-21): the bean dishes and cakes
BEAN_RECIPES = ("bean_ham_salad", "bean_medley_curry", "beanburger_curry", "cake_bean_blue", "cake_bean_green",
                "cake_bean_orange", "cake_bean_red", "cake_bean_yellow")
NEVER = {"condition": "fabric:not", "value": {"condition": "fabric:true"}}


def files():
    head = "# Generated by tools/no_beans.py; never edit (build/ is regenerated)."
    sweep = [head, "# every %d ticks: no CobbleCuisine bean stays in a player's inventory (eating one crashes the server)"
             % SWEEP_TICKS] + ["clear @a cobblecuisine:%s" % b for b in BEANS] + [
        "schedule function %s:no_beans/sweep %dt replace" % (NS, SWEEP_TICKS)]
    load = [head, "schedule function %s:no_beans/sweep %dt replace" % (NS, SWEEP_TICKS)]
    out = {
        "pack.mcmeta": json.dumps({"pack": {"pack_format": PACK_FORMAT, "description":
                                            "Cobblers: CobbleCuisine beans blocked (they crash the server on 1.8.2)"}},
                                  indent=2) + "\n",
        "data/minecraft/tags/function/load.json": json.dumps({"values": ["%s:no_beans/load" % NS]}, indent=2) + "\n",
        "data/cobblecuisine/loot_table/blocks/bean_crop.json": json.dumps({"type": "minecraft:block", "pools": []},
                                                                          indent=2) + "\n",
    }
    for r in BEAN_RECIPES:
        out["data/cobblecuisine/recipe/%s.json" % r] = json.dumps({"fabric:load_conditions": [NEVER]}, indent=2) + "\n"
    for name, lines in (("load", load), ("sweep", sweep)):
        rel = "data/%s/function/no_beans/%s.mcfunction" % (NS, name)
        bad = function_limits.check_lines(lines, rel)
        if bad:
            raise SystemExit("%s: %d command(s) the server would refuse: %s" % (rel, len(bad), bad))
        out[rel] = "\n".join(lines) + "\n"
    return out


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out", default=str(DEFAULT_OUT))
    a = p.parse_args(argv)
    out = Path(a.out)
    if out.exists():
        shutil.rmtree(out)
    for rel, text in files().items():
        f = out / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8", newline="\n")
    print("no_beans: %d beans swept every %d ticks, %d recipes closed, the bean crop drops nothing; wrote %s"
          % (len(BEANS), SWEEP_TICKS, len(BEAN_RECIPES), out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
