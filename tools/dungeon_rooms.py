class RoomError(ValueError):
    pass


def register(name, fn, **flags):
    """Register a room kind. flags: dress ("none"|"light"|"full": how much the theme may dress it), rise (may change
    floor level), connector (counts against the connector limits), pit (blocks of drop below the route a catch floor
    holds), no_deploy (Pokemon are swept out of it), jumps (the walk check allows jumps), dark (needs no light),
    length_snap / width_snap (the actual size is 'pitch*n + offset': (pitch, offset))."""
    bad = set(flags) - set(DEFAULT_FLAGS)
    if bad:
        raise RoomError("register(%s): unknown flag(s) %s" % (name, sorted(bad)))
    KINDS[name] = fn
    FLAGS[name] = dict(DEFAULT_FLAGS, **flags)
    DECLARED_KINDS.discard(name)


def declare_kind(name):
    """Name a kind that has no implementation yet (it builds as a themed empty room, with warnings)."""
    if name not in KINDS:
        DECLARED_KINDS.add(name)


def register_dress(name, fn, level="light"):
    DRESS[name] = (fn, level)


def flags_of(kind):
    load_extensions()
    return FLAGS.get(kind) or dict(DEFAULT_FLAGS, dress="full")


def known_kind(kind):
    load_extensions()
    return kind in KINDS or kind in DECLARED_KINDS


def F(name):
    return "%s:%s/%s" % (NS, FOLDER, name)


def fill(box, block, mode=None):
    return ("fill", tuple(box), block, mode) if mode else ("fill", tuple(box), block)


def setb(pos, block):
    return ("set", tuple(pos), block)


def rng(d, room, salt=""):
    """A deterministic random generator for one room, the same in every slot of the dungeon."""
    return random.Random("%s/%s/%s" % (d["id"], room["id"], salt))


def text(msg, colour="gray", italic=False):
    return json.dumps({"text": msg, "color": colour, "italic": italic}, ensure_ascii=False)


# ------------------------------------------------------------------------------------------------- themes


_THEMES = {}


def load_themes(path=THEMES_PATH):
    key = str(path)
    if key not in _THEMES:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
        if doc.get("schema") != THEMES_SCHEMA:
            raise RoomError("%s: schema must be %s" % (path, THEMES_SCHEMA))
        _THEMES[key] = doc
    return _THEMES[key]


def theme_for(d, themes=None):
    themes = themes if themes is not None else load_themes()
    t = themes["themes"].get(d.get("theme"))
    if t is None:
        raise RoomError("%s: theme %r is not in data/dungeon_themes.json" % (d["id"], d.get("theme")))
    return t


def has_rooms(d):
    return "rooms" in d


_EXTENSIONS_LOADED = []


def load_extensions():
    """Import the kind modules once, on first use: never at import time, because an extension (dungeon_fights)
    imports tools/dungeon.py, which imports this module, and a load at import time finds dungeon.py half-built."""
    if _EXTENSIONS_LOADED:
        return
    _EXTENSIONS_LOADED.append(True)
    for name in EXTENSION_MODULES:
        try:
            importlib.import_module(name)
        except ModuleNotFoundError as e:
            if e.name != name:
                raise


# ------------------------------------------------------------------------------------------------- the plan


def _snap(value, snap):
    if not snap:
        return value
    pitch, off = snap
    n = max(1, (value - off) // pitch)
    return pitch * n + off


def room_floors(room):
    """Feet level of the room's BASE floor at each interior column ix0..ix1 (a pit room's is its catch floor)."""
    return room["floors"]


def floor_at(room, x):
    return room["floors"][min(max(x - room["ix0"], 0), len(room["floors"]) - 1)]


def layout(doc, d, slot):
    """The dungeon's rooms with absolute pocket coordinates (geometry only, no anchors), for one slot.

    Each room carries its record fields and: i, theme; xa..xb / za..zb the outer box (walls included) and ix0..ix1 /
    iz0..iz1 the interior; length and width as BUILT (a kind may snap them: a maze's are 4n+3 and 4m+1); z_in, z_out the
    door lines; floor_in, floor_out the walking floor at the two doors; pit, y_lo (lowest feet level inside), hull_lo
    (the floor course under it), ceil_y (the ceiling course), floors (base floor per interior column);
    box [x0,y0,z0,x1,y1,z1] the interior, inclusive; door_in / door_out [x0,y0,z0,x1,y1,z1] (2 columns x 3 wide x 4
    high; None for the first room's in and the last room's out); gate_in the previous room's gate."""
    fy = doc["engine"]["pocket"]["floor_y"]
    x = slot["x0"]
    z_in = slot["cz"]
    floor = fy
    out = []
    prev_gate = "open"
    decl = d["rooms"]
    for i, r in enumerate(decl):
        kind = r["kind"]
        fl = flags_of(kind)
        params = r.get("params", {})
        length = _snap(r["length"], fl["length_snap"])
        width = _snap(r["width"], fl["width_snap"])
        rise = r.get("rise", 0)
        last = i == len(decl) - 1
        z_out = z_in if last else z_in + params.get("exit_dz", 0)
        gate = r.get("gate", "cleared" if kind == "boss_arena" else "open")
        pit = params.get("pit", fl["pit"])
        floor_in, floor_out = floor, floor + rise
        zlo, zhi = slot["z0"] + 1, slot["z0"] + STRIP_INTERIOR
        dmin, dmax = min(z_in, z_out), max(z_in, z_out)
        if fl["width_snap"]:
            # a grid room's rows are 4 apart with the door on a row centre: put the door row where it fits
            pitch, off = fl["width_snap"]
            rows = (width - off) // pitch
            j = round(((z_in - 2) - (slot["cz"] - (width - 1) // 2)) / pitch)
            j = min(max(j, 0), rows - 1)
            a = z_in - 2 - pitch * j
            while a < zlo and j > 0:
                j -= 1
                a = z_in - 2 - pitch * j
            while a + width - 1 > zhi and j < rows - 1:
                j += 1
                a = z_in - 2 - pitch * j
            fits = zlo <= a and a + width - 1 <= zhi
        else:
            lo = max(zlo, dmax + 2 - (width - 1))
            hi = min(zhi - (width - 1), dmin - 2)
            fits = lo <= hi
            a = min(max(round((dmin + dmax) / 2 - (width - 1) / 2), lo), hi) if fits else lo
        xa, xb = x, x + length - 1
        ix0, ix1 = xa + 1, xb - 1
        n = ix1 - ix0 + 1
        if rise and n > 1:
            sign = 1 if rise > 0 else -1
            floors = [floor_in + sign * ((abs(rise) * c) // (n - 1)) for c in range(n)]
        else:
            floors = [floor_in] * n
        ceil_y = max(floor_in, floor_out) + r["height"]
        y_lo = min(floor_in, floor_out) - pit
        if pit:
            floors = [y_lo] * n
        room = dict(r, i=i, theme=d.get("theme"), kind=kind, params=params, gate=gate, length=length, width=width,
                    rise=rise, xa=xa, xb=xb, ix0=ix0, ix1=ix1, za=a - 1, zb=a + width, iz0=a, iz1=a + width - 1,
                    z_in=z_in, z_out=z_out, floor_in=floor_in, floor_out=floor_out, pit=pit, y_lo=y_lo,
                    hull_lo=y_lo - 1, ceil_y=ceil_y, floors=floors, fits=fits, gate_in=prev_gate, last=last,
                    no_deploy=bool(params.get("no_deploy", fl["no_deploy"])))
        room["floor_y"] = floor_in
        room["box"] = [ix0, y_lo, a, ix1, ceil_y - 1, a + width - 1]
        room["door_in"] = None if i == 0 else [xa - 1, floor_in, z_in - 1, xa, floor_in + DOOR_H - 1, z_in + 1]
        room["door_out"] = None if last else [xb, floor_out, z_out - 1, xb + 1, floor_out + DOOR_H - 1, z_out + 1]
        out.append(room)
        x += length
        z_in = z_out
        floor = floor_out
        prev_gate = gate
    return out


def plan(doc, d, slot):
    """layout() plus each room's `anchors` (the kind's own over the declared defaults): the rooms as wave 2 reads them."""
    return [dict(b.room, anchors=b.anchors) for b in slot_build(doc, d, slot)]


def sel_box(box, extra=""):
    x0, y0, z0, x1, y1, z1 = box
    return "x=%d,y=%d,z=%d,dx=%d,dy=%d,dz=%d%s" % (x0, y0, z0, x1 - x0, y1 - y0, z1 - z0, ("," + extra) if extra else "")


def points(doc, slot):
    """The slot's named points and boxes (the keys tools/dungeon.py points() returns), derived from the plan."""
    d = slot["dungeon"]
    rooms = layout(doc, d, slot)
    entry = next(r for r in rooms if r["kind"] == "entry_room")
    arena = next(r for r in rooms if r["kind"] == "boss_arena")
    exit_ = next(r for r in rooms if r["kind"] == "exit_room")
    z_in = entry["z_in"]
    segs = [dict(r, h=r["height"], i=r["i"]) for r in rooms]
    y0 = min(r["hull_lo"] for r in rooms)
    y1 = max(r["ceil_y"] for r in rooms)
    za, zb = min(r["za"] for r in rooms), max(r["zb"] for r in rooms)
    x1 = rooms[-1]["xb"]
    ab = arena["box"]
    return {
        "segs": segs, "rooms": rooms,
        "arrive": (entry["xa"] + 3.5, entry["floor_in"], z_in + 0.5, -90),
        "back": (entry["xa"] + 1, entry["floor_in"], z_in),
        "back_wall_x": entry["xa"],
        "board": (entry["xa"] + (entry["xb"] - entry["xa"]) / 2.0 + 0.5, entry["floor_in"] + 1.5, entry["za"] + 1.5),
        "threshold_x": entry["xb"],
        "arena_x": arena["xa"] + 2,
        "arena_box": (ab[0], arena["floor_in"], ab[2], ab[3] - ab[0], arena["height"] - 1, ab[5] - ab[2]),
        "spot": (arena["xa"] + (2 * (arena["xb"] - arena["xa"])) // 3, arena["floor_in"], (arena["iz0"] + arena["iz1"]) // 2),
        "gate": tuple(arena["door_out"]) if arena["door_out"] else None,
        "far": (exit_["xb"] - 1, exit_["floor_in"], exit_["z_in"]),
        "far_wall_x": exit_["xb"],
        "box": (slot["x0"], y0, za, x1 - slot["x0"], y1 - y0, zb - za),
        "no_deploy": [(r["xa"], r["hull_lo"], r["za"], r["xb"] - r["xa"], r["ceil_y"] - r["hull_lo"], r["zb"] - r["za"])
                      for r in rooms if r["no_deploy"]],
        "length": x1 - slot["x0"] + 1,
    }


