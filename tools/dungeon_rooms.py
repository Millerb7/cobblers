#!/usr/bin/env python
"""The dungeon room kit: a dungeon is an ordered list of ROOMS, each a kind of space drawn in a THEME (docs/mechanics/DUNGEON_ROOMS.md).

tools/dungeon.py calls this module for any dungeon whose record has `rooms` (the old `spine.segments` path is untouched
and still builds the Night Shift's placeholder). This module imports nothing from tools/dungeon.py.

THE RECORD (data/dungeons.json, dungeons[]):
  "theme": "mine" | "jungle" | "flooded_ruin"     an id in data/dungeon_themes.json
  "rooms": [{"id", "kind", "length", "width", "height", "rise", "gate": "open"|"cleared", "params": {...}}, ...]
Rooms are laid along +x from the slot's origin, each with its own end walls; consecutive rooms share a 3-wide, 4-high
door. `length` counts both end walls, `width` is the interior, `height` the clear height above the room's highest floor.

THE INTERFACE (wave 2 builds on exactly this; nothing here needs editing to add a kind):
  plan(doc, d, slot)              [room]   the record's fields plus absolute pocket coordinates and ANCHORS (see layout())
  layout(doc, d, slot)            [room]   the same without anchors (geometry only; what points() and the checks use)
  points(doc, slot)               dict     the engine's named points (same keys as tools/dungeon.py points())
  gate_lines(doc, room, open_)    [str]    the mcfunction lines that open or close the room's door_out (pocket context)
  register(name, fn, **flags)     a KIND: fn(doc, d, slot, room, theme) -> {"blocks": [op], "anchors": {}, "functions": {}}
  register_dress(name, fn, level) a DRESSING op named in a theme's "dress" list
  slot_build(doc, d, slot)        [Built]  every room built (cached): ops, anchors, functions, lights, grid
  shell_functions / runtime_functions / reset_lines / rooms_lines / problems / warnings   used by tools/dungeon.py

An op is ("fill", box, block[, mode]) or ("set", pos, block); mode is None, "keep" or "replace <block>".
A kind's "functions" keys: enter, clear, reset, tick are MERGED into the generated room functions of those names; any
other key becomes room/<dungeon>/<room>/s<k>/<key>. Hooks:
  room/<dungeon>/<room>/s<k>/enter   once per run, as the member who first stands in the room's box, at their position
  room/<dungeon>/<room>/s<k>/tick    every keeper pass, as the member in the room's box (clock running)
  room/<dungeon>/<room>/s<k>/clear   any context (use `execute in <pocket>` for block writes); idempotent; opens door_out
  room/<dungeon>/<room>/clear        the same, as a MEMBER, dispatching on their slot (dg.slot)
  room/<dungeon>/<room>/s<k>/reset   at the slot's reset, as the entrant, in the pocket's dimension

Anchors are named points: [x, y, z] or [x, y, z, yaw] (block coordinates; the thing stands at +0.5), lists of those, or
a 6-int box for BOX_ANCHORS. Yaw: 0 faces +z (south), 90 faces -x (west), -90 faces +x (east), 180 faces -z (north).
"""
