def runtime_functions(doc, d, slots_of_d):
    """Every generated room function for the dungeon, all its slots. Returns {name: lines}."""
    out = {}
    themes = load_themes()
    theme = theme_for(d, themes)
    for slot in slots_of_d:
        builts = slot_build(doc, d, slot)
        g = slot["g"]
        for b in builts:
            r = b.room
            h = state_holder(slot, r)
            ex = b.functions
            box = sel_box(r["box"])
            pk = "tag=dg.pk," + box
            clear = [HEAD, LOADED, "# room %s (%s), slot %d: its way on opens. Idempotent; block writes carry `in`" % (r["id"], r["kind"], g),
                     "execute if score %s dg.rs matches 2 run return 0" % h,
                     "scoreboard players set %s dg.rs 2" % h]
            if r["door_out"] and r["gate"] == "cleared":
                clear += ["execute in %s run %s" % (doc["engine"]["pocket"]["dimension"], ln) for ln in gate_lines(doc, r, True, theme)]
                if not r["params"].get("quiet", r["kind"] == "boss_arena"):
                    clear += ["execute as @a[%s] at @s run playsound minecraft:block.iron_door.open master @s ~ ~ ~ 1 0.8" % pk,
                              "title @a[%s] actionbar %s" % (pk, text(r["params"].get("cue", theme["messages"]["clear"]), "light_purple"))]
            clear += ex.get("clear", [])
            enter = [HEAD, LOADED, "# room %s (%s), slot %d: the first time the member stands in it this run (as them, at them)" % (r["id"], r["kind"], g),
                     "execute unless score %s dg.rs matches 0 run return 0" % h,
                     "scoreboard players set %s dg.rs 1" % h] + ex.get("enter", [])
            reset = [HEAD, "# room %s (%s), slot %d: the mutable blocks and this room's state back to the run's start" % (r["id"], r["kind"], g),
                     "scoreboard players set %s dg.rs 0" % h]
            if r["door_out"] and r["gate"] == "cleared":
                reset += gate_lines(doc, r, False, theme)
            reset += ex.get("reset", [])
            out["room/%s/%s/s%d/clear" % (d["id"], r["id"], slot["g"])] = clear
            out["room/%s/%s/s%d/enter" % (d["id"], r["id"], slot["g"])] = enter
            out["room/%s/%s/s%d/reset" % (d["id"], r["id"], slot["g"])] = function_limits.ensure_loaded(reset)
            if ex.get("tick"):
                out["room/%s/%s/s%d/tick" % (d["id"], r["id"], slot["g"])] = [HEAD, LOADED, "# room %s, slot %d: each pass the member is in it" % (r["id"], g)] + ex["tick"]
            for k, v in ex.items():
                if k not in ("enter", "clear", "reset", "tick"):
                    out["room/%s/%s/s%d/%s" % (d["id"], r["id"], slot["g"], k)] = list(v)
    # (no per-room member dispatch room/<d>/<room>/clear: every kind calls its slot's own s<g>/clear, so a dispatcher is a
    # function no step or pack runs, which prepare's orphan check refuses; 2026-10-09)
    return out


def rooms_lines(doc, slot):
    """slot/s<g>/rooms: as the member (clock running), each pass: first entries, then the room ticks."""
    d = slot["dungeon"]
    lines = [HEAD, "# As slot %d's member, each pass with the clock running: the room they stand in (box tests on @s are" % slot["g"],
             "# coordinate-only; m/member has already put out anyone not in the pocket)"]
    for b in slot_build(doc, d, slot):
        r = b.room
        box = sel_box(r["box"])
        lines.append("execute if entity @s[%s] if score %s dg.rs matches 0 run function %s"
                     % (box, state_holder(slot, r), room_fn(d, r, slot, "enter")))
        if b.functions.get("tick"):
            lines.append("execute if entity @s[%s] run function %s" % (box, room_fn(d, r, slot, "tick")))
    return lines


