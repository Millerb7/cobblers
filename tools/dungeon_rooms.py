def _touch(far, near):
    """How two laid rooms touch: (side of far's wall, lo, hi) the interior overlap along it, or None."""
    if far["za"] == near["zb"] + 1:
        return "north", max(far["ix0"], near["ix0"]), min(far["ix1"], near["ix1"])
    if far["zb"] + 1 == near["za"]:
        return "south", max(far["ix0"], near["ix0"]), min(far["ix1"], near["ix1"])
    if far["xa"] == near["xb"] + 1:
        return "west", max(far["iz0"], near["iz0"]), min(far["iz1"], near["iz1"])
    if far["xb"] + 1 == near["xa"]:
        return "east", max(far["iz0"], near["iz0"]), min(far["iz1"], near["iz1"])
    return None


def _yspan(r):
    return r["hull_lo"], r["ceil_y"]


def place_shortcuts(rooms):
    """Every room's `shortcuts`: a door through its wall and the touching earlier room's (DUNGEON_ROOMS.md 1a). Errors
    are kept on the far room (`layout_errors`) for plan_problems()."""
    by_id = {r["id"]: r for r in rooms}
    for far in rooms:
        for k, sc in enumerate(far.get("shortcuts") or []):
            err = far.setdefault("layout_errors", [])
            near = by_id.get(sc.get("to"))
            if near is None or near["i"] >= far["i"]:
                err.append("shortcut %s: 'to' must name an earlier room (%r)" % (sc.get("id"), sc.get("to")))
                continue
            t = _touch(far, near)
            if t is None:
                err.append("shortcut %s: room %s does not touch room %s (their walls must be side by side)"
                           % (sc.get("id"), far["id"], near["id"]))
                continue
            side, lo, hi = t
            if hi - lo + 1 < 7:
                err.append("shortcut %s: the rooms share only %d blocks of wall (7 needed)" % (sc.get("id"), max(0, hi - lo + 1)))
                continue
            c = min(max(lo + 2 + int(sc.get("at", (hi - lo) // 2 - 2)), lo + 2), hi - 2)
            if side in ("north", "south"):
                yf, yn = door_floor(far, c), door_floor(near, c)
            else:
                yf = door_floor(far, far["ix0"] if side == "west" else far["ix1"])
                yn = door_floor(near, near["ix1"] if side == "west" else near["ix0"])
            if yf != yn:
                err.append("shortcut %s: the floors differ at the door (%d in %s, %d in %s)" % (sc.get("id"), yf, far["id"], yn, near["id"]))
                continue
            if yf + DOOR_H + 1 > min(far["ceil_y"], near["ceil_y"]):
                err.append("shortcut %s: no room for a door under the ceilings" % sc.get("id"))
                continue
            box = _door_box(side, c, yf, wall_line(far, side))
            sid = sc.get("id", "c%d" % k)
            far.setdefault("shortcut_doors", []).append({"side": side, "c": c, "y": yf, "dir": "out", "to": near["i"], "main": False,
                                                        "shortcut": sid, "k": k, "gate": "shortcut", "box": box})
            near.setdefault("shortcut_doors", []).append({"side": OPP[side], "c": c, "y": yf, "dir": "in", "to": far["i"], "main": False,
                                                         "shortcut": sid, "k": k, "gate": "shortcut", "box": box})


def shortcut_hooks(doc, d, slot, room, theme):
    """The far room's tick watches the cells inside each shortcut door and opens it, once a run, from that side only."""
    out = {"functions": {}, "anchors": {}}
    dim = doc["engine"]["pocket"]["dimension"]
    for door in room.get("shortcut_doors", []):
        x, y, z = inner_cell(room, door)
        if door["dir"] == "in":
            out["anchors"].setdefault("shortcut_back", []).append([x, y, z])
            continue
        out["anchors"].setdefault("shortcut", []).append([x, y, z])
        h = "%sc%d" % (state_holder(slot, room), door["k"])
        name = "shortcut_%s" % door["shortcut"]
        dx, dz = INWARD[door["side"]]
        cells = [(x + dx * k + (w if dz else 0), z + dz * k + (w if dx else 0)) for k in range(2) for w in (-1, 0, 1)]
        bx = (min(c[0] for c in cells), y, min(c[1] for c in cells), max(c[0] for c in cells), y + 1, max(c[1] for c in cells))
        out["functions"].setdefault("tick", []).append(
            "execute if score %s dg.rs matches 0 if entity @s[%s] run function %s" % (h, sel_box(bx), room_fn(d, room, slot, name)))
        b = door["box"]
        out["functions"][name] = [
            HEAD, LOADED, "# room %s, slot %d: shortcut %s opens from this (the far) side, once a run; the slot reset shuts it"
            % (room["id"], slot["g"], door["shortcut"]),
            "execute if score %s dg.rs matches 1.. run return 0" % h,
            "scoreboard players set %s dg.rs 1" % h,
            "execute in %s run fill %d %d %d %d %d %d minecraft:air" % ((dim,) + tuple(b)),
            "execute at @s run playsound minecraft:block.iron_door.open master @s ~ ~ ~ 1 0.6",
            "title @s actionbar %s" % text(theme["messages"].get("shortcut", "A way back opens."), "gray")]
        out["functions"].setdefault("reset", []).extend([
            "scoreboard players set %s dg.rs 0" % h,
            "fill %d %d %d %d %d %d %s" % (tuple(b) + (gate_block(theme),))])
    return out


def room_start(room):
    """The walk's start: the cell just inside the main door in, at its floor (the entry room's arrival), as
    walk_problems takes it."""
    if room["kind"] == "entry_room":
        return room["xa"] + 3, room["floor_in"], room["z_in"]
    door = main_door(room, "in")
    if door is not None:
        return inner_cell(room, door)
    return room["ix0"], room["floor_in"], room["z_in"]


def room_end(room):
    """The walk's goal: the cell inside the main door out at its floor (the exit room's far rip; a dead end: None)."""
    if room["kind"] == "exit_room":
        return room["xb"] - 1, room["floor_in"], room["z_in"]
    door = main_door(room, "out")
    if door is not None:
        return inner_cell(room, door)
    return None


def pits(grid, start, jumps, cls=None):
    """Local standable cells a player can get INTO but not back out of: the walk (reversible edges) never enters them,
    so it cannot see them. Two shapes, both found by DG-AUDIT (2026-10-09) after dressing made them: (a) a drop of two
    or more from a walked cell into a neighbouring column that lands outside the walk (a 1x1 water hole between a column
    and a wall); (b) a standable cell outside the walk whose four sides are shut at body height (a 1x1 shaft between
    trunks, reached by climbing). Rooms with a catch floor (parkour, the collapse bridge) are made of drops on purpose
    and are not asked.

    A block that stops a body but holds nobody up (G.NOSUP: a big dripleaf) is asked both ways and the pits united: as
    an obstacle (it blocks the way out of a nook a jump got into: the independent audit's TRAP on a shaped jungle drift)
    and as air (a player who stands on it falls into its cell: LIFE's TRAP at jungle `treasury`)."""
    cls = grid.cls() if cls is None else cls
    if (cls == G.NOSUP).any():
        as_air = cls.copy()
        as_air[as_air == G.NOSUP] = G.PASS
        return _pits(grid, start, jumps, cls) | _pits(grid, start, jumps, as_air)
    return _pits(grid, start, jumps, cls)


def _pits(grid, start, jumps, cls):
    st, p = G.standable(cls)
    nx, ny, nz = st.shape
    reach = G.walk(grid, [start], jumps=jumps, cls=cls)
    if start not in reach:
        return set()
    out = set()
    dirs = ((1, 0), (-1, 0), (0, 1), (0, -1))
    for x, y, z in reach:
        for dx, dz in dirs:
            ax, az = x + dx, z + dz
            if not (0 <= ax < nx and 0 <= az < nz) or not (p[ax, y, az] and p[ax, y + 1, az]):
                continue
            cy = y
            while cy > 1 and not st[ax, cy, az] and p[ax, cy - 1, az]:
                cy -= 1
            if st[ax, cy, az] and cy < y - 1 and (ax, cy, az) not in reach:
                out.add((ax, cy, az))
    for x, y, z in zip(*st.nonzero()):
        c = (int(x), int(y), int(z))
        if c in reach or c in out or y + 2 >= ny:
            continue
        shut = all(not (0 <= x + dx < nx and 0 <= z + dz < nz) or not (p[x + dx, y, z + dz] or p[x + dx, y + 1, z + dz])
                   for dx, dz in dirs)
        if shut and p[x, y + 2, z]:
            out.add(c)
    out |= jump_pits(st, p, reach, G.walk(grid, [start], jumps=True, cls=cls, strict=True))
    return out


def jump_pits(st, p, reach, reach_j):
    """(c), found by the independent audit on a shaped jungle drift (KIT2, 2026-10-10): a player can always JUMP. A flat
    jump of a gap up to 3 (DUNGEONS.md V6), then any fall, from a walked cell, landing on a cell that even the jumping
    walk (reversible jumps) cannot leave: a nook behind a dripleaf or a trunk, jumped into and never out of."""
    nx, ny, nz = st.shape
    out = set()
    for x, y, z in reach:
        if y + 3 >= ny:
            continue
        for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            for n in range(2, G.JUMP_FLAT_MAX + 1):
                tx, tz = x + dx * n, z + dz * n
                if not (0 <= tx < nx and 0 <= tz < nz):
                    break
                if not all(p[x + dx * k, y + 1, z + dz * k] and p[x + dx * k, y + 2, z + dz * k] for k in range(1, n + 1)):
                    break
                cy = y + 1
                while cy > 1 and not st[tx, cy, tz] and p[tx, cy - 1, tz]:
                    cy -= 1
                if st[tx, cy, tz] and cy <= y and (tx, cy, tz) not in reach_j:
                    out.add((tx, cy, tz))
    return out


def plug_pits(ctx, fl):
    """Raise the floor of every pit (pits()) one block at a time, in the hull's floor block, until none is left: a pit
    the dressing made is a cell a player cannot leave (the owner's rule), and filling it costs the look nothing."""
    grid, room = ctx.grid, ctx.room
    start = grid.local(*room_start(room))
    x0, y0, z0 = grid.box[:3]
    block = ctx.theme["hull"]["floor"]
    for _ in range(24):
        found = pits(grid, start, fl["jumps"])
        if not found:
            return
        for lx, ly, lz in sorted(found):
            for k in range(2):      # the landing cell and the one above: a fall of two is undone in one pass
                if ly + k < grid.shape[1] - 2:
                    ctx.add(("set", (x0 + lx, y0 + ly + k, z0 + lz), block))
    raise RoomError("%s room %s: pits the dressing made are still there after 24 passes" % (ctx.d["id"], room["id"]))


