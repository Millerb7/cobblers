def op_line(op):
    if op[0] == "set":
        x, y, z = op[1]
        return "setblock %d %d %d %s" % (x, y, z, op[2])
    x0, y0, z0, x1, y1, z1 = G.norm_box(op[1])
    mode = op[3] if len(op) > 3 and op[3] else ""
    return "fill %d %d %d %d %d %d %s%s" % (x0, y0, z0, x1, y1, z1, op[2], (" " + mode) if mode else "")


def op_volume(op):
    if op[0] == "set":
        return 1
    x0, y0, z0, x1, y1, z1 = G.norm_box(op[1])
    return (x1 - x0 + 1) * (y1 - y0 + 1) * (z1 - z0 + 1)


def shell_lines(built):
    return [op_line(op) for op in built.ops + built.gate_ops]


def shell_blocks(built):
    return sum(op_volume(op) for op in built.ops + built.gate_ops)


def shell_functions(doc, slot):
    """{function name: lines} for the slot's shell: shells/s<g> calls shells/s<g>/<room> per room (each its own file,
    so no single function holds the tick long: EXP-081). engine.slots.clear_strip airs the whole strip first."""
    d = slot["dungeon"]
    out = {}
    calls = [HEAD, "# slot %d's shell, room by room (place carries the dimension in)" % slot["g"]]
    sl = doc["engine"]["slots"]
    if sl.get("clear_strip"):
        fy = doc["engine"]["pocket"]["floor_y"]
        name = "shells/s%d/clear" % slot["g"]
        out[name] = function_limits.ensure_loaded(
            ["# slot %d: the whole strip aired first (engine.slots.clear_strip; a re-apply step only, never at entry)" % slot["g"],
             "fill %d %d %d %d %d %d minecraft:air" % (slot["x0"], fy - 1 - 16, slot["z0"], slot["x0"] + sl["strip_length"] - 1,
                                                       fy - 2 + sl["clear_strip_height"], slot["z0"] + sl["strip_width_max"] - 1)])
        calls.append("function %s" % F(name))
    for b in slot_build(doc, d, slot):
        r = b.room
        name = "shells/s%d/%s" % (slot["g"], r["id"])
        lines = function_limits.ensure_loaded(
            ["# slot %d, room %d %s (%s): %d blocks written" % (slot["g"], r["i"], r["id"], r["kind"], shell_blocks(b))]
            + shell_lines(b))
        out[name] = lines
        calls.append("function %s" % F(name))
    out["shells/s%d" % slot["g"]] = calls
    return out


