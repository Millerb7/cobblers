class Probe:
    """What one probe adds to the common frame."""

    def __init__(self, pid):
        self.pid = pid
        self.objs = {}          # name -> criterion, beyond st, r, rx, ry, rz
        self.build = []         # block writes, in the pocket's context, inside the held chunks
        self.boxes = []         # (x0, y0, z0, x1, y1, z1) cleared to air by cleanup; their union is force-loaded
        self.arrive = None      # (x, y, z, yaw) for enter, or None: no owner leg
        self.fns = {}           # name -> lines
        self.files = {}         # pack path -> text
        self.loops = []         # function names cleanup unschedules
        self.ready_extra = []
        self.cleanup_extra = []
        self.consts = {}        # #name -> value on dp<id>.st


def union(boxes):
    return (min(b[0] for b in boxes), min(b[1] for b in boxes), min(b[2] for b in boxes),
            max(b[3] for b in boxes), max(b[4] for b in boxes), max(b[5] for b in boxes))


def chunk_rows(x0, z0, x1, z1):
    """forceload boxes for (x0..x1, z0..z1): one per run of chunks along a chunk row, each under 256 chunks."""
    out = []
    for cz in range(z0 // 16, z1 // 16 + 1):
        a = x0 // 16
        while a <= x1 // 16:
            b = min(x1 // 16, a + function_limits.FORCELOAD_CHUNK_LIMIT - 1)
            out.append((a * 16, cz * 16, b * 16 + 15, cz * 16 + 15))
            a = b + 1
    return out


def common(doc, P):
    """setup, setup_in, ready, cleanup, cleanup_in, cleanup_end, enter, leave, go for one probe."""
    pid, dim = P.pid, doc["dimension"]
    ST, R = O(pid, "st"), O(pid, "r")
    E, M = "dp%s.e" % pid, "dp%s.m" % pid
    u = union(P.boxes)
    ebox = sel((u[0], 0, u[2], u[3], 255, u[5]))
    fl = chunk_rows(u[0], u[2], u[3], u[5])
    objs = {"st": "dummy", "r": "dummy"}
    if P.arrive:
        objs.update({"rx": "dummy", "ry": "dummy", "rz": "dummy"})
    objs.update(P.objs)
    out = {}
    out["setup"] = [
        HEAD,
        "# Over RCON: function %s. Builds probe %s in %s and opens it %d ticks later (ready)." % (F(pid, "setup"), pid.upper(), dim, READY_TICKS),
        "# Run it again after any server restart before summoning anything (forced chunks reload, entities arrive late).",
        "execute in %s run function %s" % (dim, F(pid, "setup_in")),
        "return 1"]
    out["setup_in"] = [
        HEAD,
        "# in %s (setup carries it in). The chunks are force-loaded here and HELD until cleanup_end." % dim] + [
        "forceload add %d %d %d %d" % b for b in fl] + [
        "scoreboard objectives add %s %s" % (O(pid, k), v) for k, v in objs.items()] + [
        "scoreboard players set #ready %s 0" % ST] + [
        "scoreboard players set %s %s %d" % (k, ST, v) for k, v in P.consts.items()] + P.build + [
        "schedule function %s %dt replace" % (F(pid, "ready"), READY_TICKS)]
    out["ready"] = [
        HEAD,
        "# %d ticks after setup: the held chunks' saved entities are in (tools/chunk_look.py BLIND_TICKS). Kill what an" % READY_TICKS,
        "# earlier run left (every entity this probe summons carries %s), then open the probe." % E,
        "execute in %s store result score #stale %s if entity @e[tag=%s,%s]" % (dim, R, E, ebox),
        "execute in %s run kill @e[tag=%s,%s]" % (dim, E, ebox)] + P.ready_extra + [
        "scoreboard players set #ready %s 1" % ST,
        "tellraw @a[tag=%s] %s" % (M, text("Probe %s is ready." % pid.upper()))]
    out["cleanup"] = [
        HEAD,
        "# Over RCON, after the readings are taken (this removes every %s objective, and so every reading)." % ("dp" + pid),
        "# The owner should run leave first, so their way home is still stored.",
        "execute in %s run function %s" % (dim, F(pid, "cleanup_in")),
        "return 1"]
    clear = [l for b in P.boxes for l in function_limits.split_fills([fill(*b, "minecraft:air")])]
    out["cleanup_in"] = [
        HEAD,
        "# in %s; the chunks are still held from setup_in" % dim] + [
        "schedule clear %s" % F(pid, n) for n in P.loops + ["ready"]] + [
        "scoreboard players set #ready %s 0" % ST,
        "kill @e[tag=%s,%s]" % (E, ebox),
        "kill @e[type=minecraft:item,%s]" % ebox,
        "kill @e[type=minecraft:experience_orb,%s]" % ebox] + P.cleanup_extra + [
        "# chunks-loaded-by: %s" % F(pid, "setup_in")] + clear + [
        "schedule function %s %dt replace" % (F(pid, "cleanup_end"), READY_TICKS)]
    out["cleanup_end"] = [
        HEAD,
        "# %d ticks after cleanup: the kill again over the same window (tools/chunk_look.py sweep), then release." % READY_TICKS,
        "execute in %s run kill @e[tag=%s,%s]" % (dim, E, ebox),
        "tag @a remove %s" % M] + [
        "execute in %s run forceload remove %d %d %d %d" % ((dim,) + b) for b in fl] + [
        "scoreboard objectives remove %s" % O(pid, k) for k in objs]
    if P.arrive:
        ax, ay, az, yaw = P.arrive
        out["enter"] = [
            HEAD,
            "# Over RCON, as the owner standing in the overworld: execute as <owner> at @s run function %s" % F(pid, "enter"),
            "execute unless dimension minecraft:overworld run return 0",
            "execute unless score #ready %s matches 1 run return 0" % ST,
            "execute store result score @s %s run data get entity @s Pos[0]" % O(pid, "rx"),
            "execute store result score @s %s run data get entity @s Pos[1]" % O(pid, "ry"),
            "execute store result score @s %s run data get entity @s Pos[2]" % O(pid, "rz"),
            "tag @s add %s" % M,
            "execute in %s run tp @s %.1f %d %.1f %.0f 0" % (dim, ax, ay, az, yaw),
            "return 1"]
        out["leave"] = [
            HEAD,
            "# Over RCON: execute as <owner> run function %s -- back to where enter found them" % F(pid, "leave"),
            "execute unless entity @s[tag=%s] run return 0" % M,
            "tag @s remove %s" % M,
            "execute store result storage %s:%s go.x int 1 run scoreboard players get @s %s" % (NS, pid, O(pid, "rx")),
            "execute store result storage %s:%s go.y int 1 run scoreboard players get @s %s" % (NS, pid, O(pid, "ry")),
            "execute store result storage %s:%s go.z int 1 run scoreboard players get @s %s" % (NS, pid, O(pid, "rz")),
            "function %s with storage %s:%s go" % (F(pid, "go"), NS, pid),
            "return 1"]
        out["go"] = ["$execute in minecraft:overworld run tp @s $(x) $(y) $(z)"]
    return out


