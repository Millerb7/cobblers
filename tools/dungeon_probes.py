class ProbeError(ValueError):
    pass


def load(path=DATA):
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    if doc.get("schema") != SCHEMA:
        raise ProbeError("%s: schema must be %s" % (path, SCHEMA))
    return doc


def _j(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def probe(doc, pid):
    for p in doc["probes"]:
        if p["id"] == pid:
            return p
    raise ProbeError("no probe %r" % pid)


# ------------------------------------------------------------------------------------------------- geometry


def row_ids(doc):
    return [p["id"] for p in doc["probes"] if p["id"] != "i2"]


def area(doc, pid):
    """(x0, z0, x1, z1): the probe's whole area. i2 has its own strip; every other probe a slot in the row."""
    if pid == "i2":
        s = probe(doc, "i2")["strip"]
        return s["x0"], s["z0"], s["x0"] + s["length"] - 1, s["z0"] + s["width"] - 1
    r = doc["row"]
    x0 = r["origin_x"] + row_ids(doc).index(pid) * r["spacing"]
    return x0, r["z_min"], x0 + r["spacing"] - 1, r["z_max"]


def origin(doc, pid):
    """The probe's working centre (ox, floor_y, oz): 32 in from the area's low-x edge, on the row's middle z."""
    x0, z0, _x1, z1 = area(doc, pid)
    return x0 + 32, doc["floor_y"], (z0 + z1 + 1) // 2


def foreign_boxes(doc, portals_doc=None, entei_doc=None):
    """{name: (x0, z0, x1, z1)} of everything a probe must stay out of, each from its own data file."""
    portals_doc = portals_doc if portals_doc is not None else _j(PORTALS)
    entei_doc = entei_doc if entei_doc is not None else _j(ENTEI)
    pp = portals_doc["pocket"]
    # tools/entei_boss.py's own check, conservative: the rescue box's whole z range, on every x
    rescue = (-10 ** 6, min(pp["bands"].values()) - pp["rescue_margin"],
              10 ** 6, max(pp["bands"].values()) + pp["rescue_margin"])
    ep, half = entei_doc["pocket"], entei_doc["room"]["half"]
    xs = [ep["origin"][0] + k * ep["spacing"] for k in range(ep["slots"])]
    m = ENTEI_SWEEP_MARGIN
    entei = (min(xs) - half - m, ep["origin"][1] - half - m, max(xs) + half + m, ep["origin"][1] + half + m)
    rows = (-10 ** 6, DUNGEON_ROWS_FROM_Z, 10 ** 6, 10 ** 6)
    return {"portals rescue box": rescue, "Entei's band": entei, "dungeon slot rows": rows}


def _meets(a, b):
    return not (a[2] < b[0] or b[2] < a[0] or a[3] < b[1] or b[3] < a[1])


def problems(doc, portals_doc=None, entei_doc=None):
    bad = []
    portals_doc = portals_doc if portals_doc is not None else _j(PORTALS)
    if doc["dimension"] != portals_doc["pocket"]["dimension"]:
        bad.append("dimension %s is not data/portals.json pocket.dimension %s"
                   % (doc["dimension"], portals_doc["pocket"]["dimension"]))
    ids = [p["id"] for p in doc["probes"]]
    if len(set(ids)) != len(ids):
        bad.append("probe ids repeat")
    want = ["p1", "b1", "b2", "b3", "r1", "r2", "f1", "l1", "l2", "c1", "xt1", "v1", "i2", "lo1", "sg1"]
    if ids != want:
        bad.append("probes must be %s in that order (the EXP numbering follows it), got %s" % (want, ids))
    for n, p in enumerate(doc["probes"]):
        if p["exp"] != "EXP-%03d" % (69 + n):
            bad.append("%s: exp %s, expected EXP-%03d" % (p["id"], p["exp"], 69 + n))
    lo, hi = doc["border"][0] + doc["border_margin"], doc["border"][1] - doc["border_margin"]
    boxes = {pid: area(doc, pid) for pid in ids}
    foreign = foreign_boxes(doc, portals_doc, entei_doc)
    for pid, b in boxes.items():
        if not (lo <= b[0] and b[2] <= hi and lo <= b[1] and b[3] <= hi):
            bad.append("%s: area %s is outside the border margin %d..%d" % (pid, b, lo, hi))
        for name, f in foreign.items():
            if _meets(b, f):
                bad.append("%s: area %s meets %s %s" % (pid, b, name, f))
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            if _meets(boxes[a], boxes[b]):
                bad.append("areas of %s and %s overlap" % (a, b))
    return bad


# ------------------------------------------------------------------------------------------------- helpers


def F(pid, name):
    return "%s:%s/%s" % (NS, pid, name)


def O(pid, name):
    o = "dp%s.%s" % (pid, name)
    if len(o) > 16 or not OBJ_RE.match(o):
        raise ProbeError("objective %r is not a dp<id>.<name> of at most 16 characters" % o)
    return o


def fill(x0, y0, z0, x1, y1, z1, block, mode=""):
    return "fill %d %d %d %d %d %d %s%s" % (x0, y0, z0, x1, y1, z1, block, (" " + mode) if mode else "")


def setb(x, y, z, block):
    return "setblock %d %d %d %s" % (x, y, z, block)


def sel(box, extra=""):
    x0, y0, z0, x1, y1, z1 = box
    return "x=%d,y=%d,z=%d,dx=%d,dy=%d,dz=%d%s" % (x0, y0, z0, x1 - x0, y1 - y0, z1 - z0, ("," + extra) if extra else "")


def text(msg, colour="gray"):
    return json.dumps({"text": msg, "color": colour}, ensure_ascii=False)


def pen(cx, cz, half, y, floor="minecraft:smooth_stone", wall="minecraft:glass", h=3):
    """A floor of (2 half + 1)^2 at y - 1 and a wall ring h high round it: nobody walks off into the 96-block drop."""
    a, b = half + 1, y + h - 1
    lines = [fill(cx - a, y - 1, cz - a, cx + a, y - 1, cz + a, floor),
             fill(cx - a, y, cz - a, cx + a, b, cz - a, wall), fill(cx - a, y, cz + a, cx + a, b, cz + a, wall),
             fill(cx - a, y, cz - a, cx - a, b, cz + a, wall), fill(cx + a, y, cz - a, cx + a, b, cz + a, wall)]
    return lines, (cx - a, y - 1, cz - a, cx + a, b, cz + a)


def tube(x, z, y0, y1, wall="minecraft:glass"):
    """A 1 x 1 glass tube round column (x, z) from y0 to y1."""
    return [fill(x - 1, y0, z - 1, x + 1, y1, z - 1, wall), fill(x - 1, y0, z + 1, x + 1, y1, z + 1, wall),
            setb(x - 1, y0, z, wall) if y0 == y1 else fill(x - 1, y0, z, x - 1, y1, z, wall),
            setb(x + 1, y0, z, wall) if y0 == y1 else fill(x + 1, y0, z, x + 1, y1, z, wall)]


