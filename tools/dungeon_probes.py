def build(doc, **kw):
    bad = problems(doc, kw.get("portals_doc"), kw.get("entei_doc"))
    if bad:
        raise ProbeError("data/dungeon_probes.json: " + "; ".join(bad))
    files = {"pack.mcmeta": json.dumps({"pack": {"pack_format": PACK_FORMAT, "description":
                                                 "Cobblers: dungeon probes, STAGING ONLY (tools/dungeon_probes.py)"}},
                                       indent=2) + "\n"}
    for spec in doc["probes"]:
        P = BUILDERS[spec["id"]](doc, spec)
        fns = dict(P.fns)
        if spec["id"] != "i2":
            fns.update(common(doc, P))
        else:
            fns["setup"] = [HEAD, "# I2 needs no setup: shell, dirty and clear each force-load what they write", "return 1"]
            fns["cleanup"] = [HEAD, "return run function %s" % F("i2", "clear")]
        for name, lines in fns.items():
            rel = "data/%s/function/%s/%s.mcfunction" % (NS, spec["id"], name)
            refused = function_limits.check_lines(lines, rel)
            if refused:
                raise SystemExit("%s: %d command(s) the server would refuse (%s); nothing written"
                                 % (rel, len(refused), refused[0][2][:120]))
            files[rel] = "\n".join(lines) + "\n"
        files.update(P.files)
    return files


def write(files, out):
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    for rel, body in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8", newline="\n")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--data", default=str(DATA))
    p.add_argument("--out", default=str(DEFAULT_OUT))
    a = p.parse_args(argv)
    files = build(load(a.data))
    write(files, a.out)
    print("cobblers_dg_probes: %d files -> %s (STAGING ONLY: install by hand into the staging world's datapacks/)"
          % (len(files), a.out))
    return 0


