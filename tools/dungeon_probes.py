"""The Night Shift dungeon's probe pack: staging-only proofs that can kill a mechanism before the engine is built.

  python tools/dungeon_probes.py                 # write build/datapacks/cobblers_dg_probes
  python tools/dungeon_probes.py --out <dir>

docs/mechanics/DUNGEONS.md section 14 lists the unknowns. This pack carries one self-contained probe for each of P1,
B1, B2, B3, R1, R2, F1, L1, L2, C1, XT1, V1, I2, LO1 and SG1 (DX1 waits for the run tag, E1). Each probe has:

  - its own functions under cobblers_dg_probes:<id>/ (setup, ready, cleanup and its own steps),
  - its own scoreboard objectives, all named dp<id>.<name>,
  - its own area in cobblers:pocket (data/dungeon_probes.json row and i2's strip), disjoint from every other probe,
    from the portals' rescue box, from Entei's band and from the dungeon slots' rows (problems() refuses an overlap),
  - its own explicit reading, in experiments/EXP-069 .. EXP-083.

STAGING ONLY. The pack is world-local and installed by hand into the staging world's datapacks/ folder. It is never in
the players' pack and never in tools/reapply.py's install lists (tests/test_dungeon_probes.py holds both). It has NO
load or tick tag: nothing runs until the session calls a probe's setup over RCON, and everything works after a plain
restart (a 12G staging server cannot /reload this build, review N111). The only things it does on its own are its
three Cobblemon callbacks, and each of them acts only on an entity carrying that probe's own tag (P1's on a Pokemon
standing inside P1's box in the pocket).

Looking before acting (review N155, tools/chunk_look.py). Every probe's setup force-loads its chunks and HOLDS them
until its cleanup, and schedules <id>/ready BLIND_TICKS (300) later. ready kills whatever tagged entities an earlier
run left (their chunks have been loaded the whole window), then opens the probe. Every function that summons refuses
until ready has run. A probe's first run has nothing saved to look for, so the blind wait is the whole look; chunk_look's
chain is not used because it releases its forceload when it is done, and a probe must keep its chunks for its life.
cleanup kills at once and again BLIND_TICKS later (chunk_look.sweep's repeat over the same window) before it releases
the chunks. After a server restart, run the probe's setup again before summoning anything: forced chunks reload and
their entities arrive late.

Ownership: data/dungeon_probes.json is the source; the pack is generated into build/ (gitignored); the tests are
tests/test_dungeon_probes.py, written to check isolation and validity only (they prove nothing about behaviour).
"""
