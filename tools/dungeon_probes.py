def _merge_rows(fl):
    """chunk_rows gives one box per chunk row; merge vertically adjacent rows with the same x span while the box
    stays within 256 chunks (DUNGEONS.md 11.3: 'two batches' for a 2,048 x 64 strip)."""
    out = []
    for b in fl:
        if out:
            a = out[-1]
            n = ((b[2] - a[0]) // 16 + 1) * ((b[3] - a[1]) // 16 + 1)
            if a[0] == b[0] and a[2] == b[2] and a[3] + 1 == b[1] and n <= function_limits.FORCELOAD_CHUNK_LIMIT:
                out[-1] = (a[0], a[1], a[2], b[3])
                continue
        out.append(b)
    return out


