def _chain(doc, pid, P, stages, gap, prefix, timed, next_extra=(), done_title="The chain is over."):
    """The staged boss's chain (DUNGEONS.md 3.2): stage k's class spawned at the stand, the battle started 20 ticks
    later; the victory callback tags the owner; the keeper's first pass with in_battle 0 kills the stage, and the
    next stage starts `gap` ticks after that (spawn at gap - 20, start at gap)."""
    dim = doc["dimension"]
    ox, oy, oz = origin(doc, pid)
    ST, R = O(pid, "st"), O(pid, "r")
    npc, own = "dp%s.npc" % pid, "dp%s.m" % pid
    inner = sel(P.boxes[0])
    n = len(stages)
    spawn = [HEAD, "# stage #stage's class at the stand; the battle starts 20 ticks later (go)",
             "execute in %s run kill @e[type=cobblemon:npc,tag=%s,%s]" % (dim, npc, inner)]
    for k in range(1, n + 1):
        spawn += ["execute if score #stage %s matches %d run function %s" % (ST, k, F(pid, "%sspawn_%d" % (prefix, k)))]
        P.fns["%sspawn_%d" % (prefix, k)] = [HEAD] + spawn_npc_lines(
            doc, pid, F(pid, "npc_at"), ox + 0.5, oy, oz + 3.5, stages[k - 1], 5, ["dp%s.e" % pid, npc])
    spawn += ["schedule function %s 20t replace" % F(pid, prefix + "go")]
    P.fns[prefix + "spawn_stage"] = spawn
    go = [HEAD, "execute unless score #arm %s matches 1 run return 0" % ST,
          "execute store result score #t_go %s run time query gametime" % R,
          "execute if score #stage %s matches 2.. run scoreboard players add #follow %s 1" % (ST, R),
          "execute if score #stage %s matches 2.. run scoreboard players operation #gap_last %s = #t_go %s" % (ST, R, R),
          "execute if score #stage %s matches 2.. run scoreboard players operation #gap_last %s -= #t_seen %s" % (ST, R, R)]
    if timed:
        go += ["scoreboard players operation #t0 %s = #t_go %s" % (R, R),
               "execute if score #stage %s matches 1 run scoreboard players operation #chain_t0 %s = #t_go %s" % (ST, R, R)]
    go += [start_battle_line(pid, npc, own)]
    P.fns[prefix + "go"] = go
    P.fns[prefix + "keeper"] = [
        HEAD, "# every 20 ticks while a chain runs",
        "execute unless score #arm %s matches 1 run return 0" % ST,
        "scoreboard players add #passes %s 1" % R,
        "execute as @a[tag=%s,tag=dp%s.lost] run function %s" % (own, pid, F(pid, prefix + "lost")),
        "execute as @a[tag=%s,tag=dp%s.won,limit=1] at @s run runmolang \"(q.player.in_battle == 0) ? { "
        "q.run_command('function %s'); };\" @s" % (own, pid, F(pid, prefix + "next")),
        "execute if score #arm %s matches 1 run schedule function %s 20t replace" % (ST, F(pid, prefix + "keeper"))]
    P.fns[prefix + "next"] = [
        HEAD, "# from the keeper's runmolang (queued, as the server): the owner won and is out of the battle",
        "execute unless entity @a[tag=%s,tag=dp%s.won] run return 0" % (own, pid),
        "tag @a[tag=%s] remove dp%s.won" % (own, pid)] + list(next_extra) + [
        "execute store result score #t_seen %s run time query gametime" % R,
        "execute in %s run kill @e[type=cobblemon:npc,tag=%s,%s]" % (dim, npc, inner),
        "scoreboard players add #stage %s 1" % ST,
        "execute if score #stage %s matches ..%d run title @a[tag=%s] title %s" % (ST, n, own, text("He gets up again.", "dark_red")),
        "execute if score #stage %s matches ..%d run schedule function %s %dt replace" % (ST, n, F(pid, prefix + "spawn_stage"), gap - 20),
        "execute if score #stage %s matches %d.. run function %s" % (ST, n + 1, F(pid, prefix + "done"))]
    P.fns[prefix + "lost"] = [HEAD, "# as the owner, beaten by a stage: the chain is over",
                              "tag @s remove dp%s.lost" % pid, "scoreboard players add #lost %s 1" % R,
                              "scoreboard players set #arm %s 0" % ST,
                              "execute in %s run kill @e[type=cobblemon:npc,tag=%s,%s]" % (dim, npc, inner)]
    P.fns[prefix + "done"] = [HEAD, "scoreboard players set #done %s 1" % R, "scoreboard players set #arm %s 0" % ST,
                              "title @a[tag=%s] title %s" % (own, text(done_title, "gold"))]
    P.loops += [prefix + "keeper", prefix + "spawn_stage", prefix + "go"]


