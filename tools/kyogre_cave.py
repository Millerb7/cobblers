def forceloads(boxes, verb):
    seen, out = set(), []
    for x0, z0, x1, z1 in boxes:
        k = (x0 // 16, z0 // 16, x1 // 16, z1 // 16)
        if k in seen:
            continue
        seen.add(k)
        out.append("forceload %s %d %d %d %d" % (verb, x0, z0, x1, z1))
    return out


