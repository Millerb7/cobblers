def _fill(x1: int, y1: int, z1: int, x2: int, y2: int, z2: int, block: str) -> str:
    return f"fill ~{x1} ~{y1} ~{z1} ~{x2} ~{y2} ~{z2} {block}"


def _set(x: int, y: int, z: int, block: str) -> str:
    return f"setblock ~{x} ~{y} ~{z} {block}"


def _island_commands(seed: int) -> list[str]:
    rng = random.Random(seed)
    commands = [
        "# Generated by tools/generate_f4_relic_island.py",
        "# Execute positioned at the island center with ~0 at sea level.",
        "forceload add ~-42 ~-35 ~42 ~35",
    ]
    rx, rz = 35, 29
    jitters = {z: rng.choice((-2, -1, 0, 0, 0, 1, 2)) for z in range(-rz, rz + 1)}
    for z in range(-rz, rz + 1):
        curve = math.sqrt(max(0.0, 1.0 - (z / rz) ** 2))
        width = max(2, round(rx * curve) + jitters[z])
        commands.append(_fill(-width, -6, z, width, -3, z, "minecraft:stone"))
        if width > 3:
            commands.append(_fill(-width + 2, -2, z, width - 2, -1, z, "minecraft:gravel"))
        if width > 6:
            commands.append(_fill(-width + 4, 0, z, width - 4, 0, z, "minecraft:sand"))
        if abs(z) <= 23 and width > 10:
            inner = width - 8
            commands.append(_fill(-inner, 1, z, inner, 2, z, "minecraft:dirt"))
            commands.append(_fill(-inner, 3, z, inner, 3, z, "minecraft:grass_block"))
        if abs(z) <= 17 and width > 14:
            inner = width - 12
            commands.append(_fill(-inner, 4, z, inner, 4, z, "minecraft:grass_block"))
    return commands


