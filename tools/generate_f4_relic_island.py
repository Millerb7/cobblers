def generate(
    source: Path,
    function_path: Path,
    preview_path: Path,
    template_source: Path,
    template_output: Path,
) -> dict[str, str | int]:
    config = json.loads(source.read_text(encoding="utf-8"))
    seed = int(hashlib.sha256(config["id"].encode()).hexdigest()[:8], 16)
    commands = _island_commands(seed) + _donor_commands()
    function_path.parent.mkdir(parents=True, exist_ok=True)
    preview_path.parent.mkdir(parents=True, exist_ok=True)
    template_output.parent.mkdir(parents=True, exist_ok=True)
    function_path.write_text("\n".join(commands) + "\n", encoding="utf-8", newline="\n")
    preview_path.write_text(_preview(config), encoding="utf-8", newline="\n")
    shutil.copyfile(template_source, template_output)
    return {
        "commands": len([line for line in commands if line and not line.startswith("#")]),
        "function_sha256": hashlib.sha256(function_path.read_bytes()).hexdigest(),
        "preview_sha256": hashlib.sha256(preview_path.read_bytes()).hexdigest(),
        "template_sha256": hashlib.sha256(template_output.read_bytes()).hexdigest(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--function", type=Path, default=DEFAULT_FUNCTION)
    parser.add_argument("--preview", type=Path, default=DEFAULT_PREVIEW)
    parser.add_argument("--template-source", type=Path, default=DEFAULT_TEMPLATE_SOURCE)
    parser.add_argument("--template-output", type=Path, default=DEFAULT_TEMPLATE_OUTPUT)
    args = parser.parse_args()
    result = generate(
        args.source,
        args.function,
        args.preview,
        args.template_source,
        args.template_output,
    )
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
